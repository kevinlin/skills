def check(label, ok, detail=''):
    RESULTS.append((label, bool(ok)))
    line = ('PASS ' if ok else 'FAIL ') + label
    if not ok and detail:
        line += ' -- ' + re.sub(r'\s+', ' ', str(detail))[:400]
